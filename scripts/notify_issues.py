#!/usr/bin/env python3
"""Post today's registry changes as comments on one GitHub issue per trial, so people can Subscribe.

Inert unless the workflow runs it (repository variable NOTIFY_ISSUES = true). For each trial with an
entry in data/changes.yaml observed today, finds the open issue labelled `trial-updates` whose title
starts with the registry ID, creating it if missing, and posts one comment listing the changes.
Issue bodies and comments contain only the generated change lines and registry links; never any
person's data. Needs the gh CLI with GH_TOKEN and PyYAML. Usage: python3 scripts/notify_issues.py [YYYY-MM-DD]
"""
import sys, json, pathlib, datetime, subprocess, collections
import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
LABEL = "trial-updates"

def gh(*args, input=None):
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True, input=input).stdout

def main():
    today = sys.argv[1] if len(sys.argv) > 1 else datetime.date.today().isoformat()
    changes = yaml.safe_load((ROOT / "data" / "changes.yaml").read_text()) or []
    todays = collections.defaultdict(list)
    for c in changes:
        if str(c.get("date_observed")) == today:
            todays[c["registry_id"]].append(c)
    if not todays:
        print("no changes observed today; nothing to post"); return
    try:
        gh("label", "create", LABEL, "--description", "Subscribe for registry changes to one trial", "--color", "0E8A16")
    except subprocess.CalledProcessError:
        pass  # exists
    issues = json.loads(gh("issue", "list", "--label", LABEL, "--state", "open", "--limit", "200", "--json", "number,title"))
    by_id = {i["title"].split()[0]: i["number"] for i in issues}
    for rid, cs in todays.items():
        trial = cs[0].get("trial") or rid
        url = cs[0]["registry_url"]
        body = f"Registry changes observed {today} for **{trial}** ([{rid}]({url})):\n\n" + "".join(f"- {c['detail']} (registry record updated {c.get('registry_last_updated') or 'date not given'})\n" for c in cs)
        body += "\nGenerated by scripts/pull_registry.py from the registry record. A human re-verifies the trial in data/trials.yaml before the guide changes. Navigation, not medical advice."
        if rid not in by_id:
            out = gh("issue", "create", "--title", f"{rid} {trial}: registry updates", "--label", LABEL,
                     "--body", f"Subscribe to this issue to be emailed when the registry record for **{trial}** ([{rid}]({url})) changes: new sites, status, eligibility, dates, results. Comments are posted by the nightly job; please do not post personal or medical details here.")
            by_id[rid] = int(out.strip().rsplit("/", 1)[-1])
        gh("issue", "comment", str(by_id[rid]), "--body", body)
        print(f"commented on issue #{by_id[rid]} for {rid}: {len(cs)} change(s)")

if __name__ == "__main__":
    main()
